import hashlib
import os
import uuid
from pathlib import Path
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from app.core.config import get_settings

MAX_BYTES = 10 * 1024 * 1024

def storage_dir():
    path = Path(get_settings().image_storage_dir).resolve()
    path.mkdir(parents=True, exist_ok=True)
    return path

def keys():
    settings = get_settings()
    private_path = Path(settings.image_private_key_path).resolve()
    public_path = Path(settings.image_public_key_path).resolve()
    if not private_path.is_file() or not public_path.is_file():
        raise RuntimeError("Image wrapping keys missing. Run python -m app.cli.create_image_keys")
    private = serialization.load_pem_private_key(private_path.read_bytes(), password=None)
    public = serialization.load_pem_public_key(public_path.read_bytes())
    return private, public

def encrypt_bytes(plaintext: bytes, record_id: str):
    _, public = keys()
    key = AESGCM.generate_key(bit_length=256)
    nonce = os.urandom(12)
    ciphertext = AESGCM(key).encrypt(nonce, plaintext, record_id.encode())
    wrapped = public.encrypt(key, padding.OAEP(mgf=padding.MGF1(algorithm=hashes.SHA256()), algorithm=hashes.SHA256(), label=None))
    return ciphertext, nonce, wrapped, hashlib.sha256(plaintext).hexdigest()

def decrypt_bytes(ciphertext: bytes, nonce: bytes, wrapped: bytes, record_id: str, expected_hash: str):
    private, _ = keys()
    key = private.decrypt(wrapped, padding.OAEP(mgf=padding.MGF1(algorithm=hashes.SHA256()), algorithm=hashes.SHA256(), label=None))
    plaintext = AESGCM(key).decrypt(nonce, ciphertext, record_id.encode())
    if hashlib.sha256(plaintext).hexdigest() != expected_hash:
        raise ValueError("Image integrity verification failed")
    return plaintext

def encrypted_path(record_id: str):
    # Record IDs are generated by the server; never use a user-supplied filename.
    uuid.UUID(record_id)
    return storage_dir() / f"{record_id}.enc"
